# ---------------------------------------------------------------------------
# Known LFSR sequences (from textbook examples)
# ---------------------------------------------------------------------------

# LFSR with connection polynomial x^3 + x + 1 (poly = 0b1011 reversed = 0b1101 = 13)
# Seed = 0b001, output the shifted-out bit each step
_POLY_3BIT = 0b1011  # standard form: x^3 + x + 1
# reversed form for lfsr_step = bit-reversed: bit 0→0, bit1→1, bit2→1, bit3→1 = 0b1110 = 14
_POLY_3BIT_REV = 0b1110


def _lfsr3(seed: int, n: int) -> list[int]:
    """Generate n output bits from a 3-bit LFSR (poly = x^3 + x + 1)."""
    state = seed & 0b111
    out = []
    for _ in range(n):
        out.append(state & 1)
        feedback = (state & 1) ^ ((state >> 1) & 1)  # taps at bits 0 and 1
        state = ((state >> 1) | (feedback << 2)) & 0b111
    return out


def test_bm_recovers_3bit_lfsr():
    """BM finds L=3 for a sequence generated by a 3-bit LFSR."""
    bits = _lfsr3(0b001, 20)
    L, C = berlekamp_massey(bits)
    assert L == 3
    # C[0]=1, C[1]=1 (tap at x^1), C[2]=0, C[3]=1 (tap at x^3)
    assert C[0] == 1
    assert C[3] == 1


def test_bm_linear_complexity_flat_sequence():
    """All-zeros sequence has L=0."""
    L, _ = berlekamp_massey([0] * 50)
    assert L == 0


def test_bm_linear_complexity_alternating():
    """Alternating 010101... has L=2 (recurrence s[n] = s[n-2])."""
    L, C = berlekamp_massey([i % 2 for i in range(100)])
    assert L == 2
    assert C == [1, 0, 1]  # x^2 + 1


