# PNG pair extraction
# ---------------------------------------------------------------------------


def test_extract_png_pairs():
    """Format-aware extractor pulls (type+data, crc) from a real PNG."""
    from fuzzer_tool.core.checksum_learner import ChecksumLearner

    # Minimal valid PNG: signature + IHDR chunk + IEND chunk
    sig = b"\x89PNG\r\n\x1a\n"
    ihdr_data = struct.pack(">IIBBBBB", 1, 1, 8, 2, 0, 0, 0)
    ihdr_type = b"IHDR"
    ihdr_crc_val = zlib.crc32(ihdr_type + ihdr_data) & 0xFFFFFFFF
    ihdr_chunk = (
        struct.pack(">I", len(ihdr_data)) + ihdr_type + ihdr_data + struct.pack(">I", ihdr_crc_val)
    )
    iend_chunk = (
        struct.pack(">I", 0) + b"IEND" + struct.pack(">I", zlib.crc32(b"IEND") & 0xFFFFFFFF)
    )
    png = sig + ihdr_chunk + iend_chunk

    # Use a fake fuzzer with checksum_learner=None
    class FakeFuzzer:
        checksum_learner = None

    learner = ChecksumLearner(FakeFuzzer())
    pairs = learner.extract_format_pairs(png)
    assert len(pairs) >= 2
    for data, _crc in pairs:
        assert len(data) > 0
        assert len(data) == len(b"IHDR" + ihdr_data) or len(data) == len(b"IEND")


