# End-to-end: recover a custom polynomial and compute valid checksums
# ---------------------------------------------------------------------------


def test_end_to_end_custom_poly():
    """Recover a custom poly from pairs, then compute valid checksums."""
    from fuzzer_tool.core.berlekamp_massey import recover_polynomial_gcd

    # Use a simple custom poly: x^8 + x^4 + x^3 + x^2 + 1 (reversed = 0x1D)
    # We manually compute the checksum so we know the exact poly.
    CUSTOM_POLY = 0x1D  # reversed form for width=8
    pairs = []
    for i in range(64):
        data = bytes([i])
        expected = compute_checksum(data, poly=CUSTOM_POLY, width=8)
        pairs.append((data, expected))

    poly = recover_polynomial_gcd(pairs, width=8)
    assert poly is not None
    # Normalize: strip trailing zeros
    norm = poly
    while norm and not (norm & 1):
        norm >>= 1
    # The GCD should be a multiple of the generator; the normalized form
    # may differ by a factor (x) if the poly has a zero coefficient.
    # Verify by round-trip: poly found should reproduce all checksums.
    for data, expected in pairs:
        got = compute_checksum(data, poly=norm, width=8)
        assert got == expected, f"round-trip failed for {data!r}: {got} != {expected}"


