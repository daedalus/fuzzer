"""Regression tests: Berlekamp-Massey algorithm + LFSR helpers.

Covers:
1. BM on known short LFSR sequences (verifiable by hand)
2. `recover_lfsr` recovers the correct polynomial from output values
3. `compute_checksum` produces identical results to `zlib.crc32` for the
   standard polynomial
4. `linear_complexity` increases with sequence length
5. `recover_polynomial_gcd` recovers the standard CRC-32 polynomial from
   enough independent (data, checksum) pairs
6. End-to-end: recover a custom non-standard polynomial, then compute
   valid checksums with it
"""

